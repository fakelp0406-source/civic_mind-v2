"""Write a review package for a document batch: what a person needs to decide, nothing applied.

Reads the batch's document manifests (``data/doc_manifests/``) and writes
``docs/acquisition/<batch>/REVIEW_PACKAGE.md`` with, for every prepared document: provenance,
the exact source SHA-256 and page-file SHA-256 an approval must bind to, extraction coverage,
every finding with its pages, and a short excerpt of the first pages that have text (to check
the printed title). It ends with a **template** of decisions. The template is not the decisions
file: nothing is approved until a person writes ``DOCUMENT_REVIEW_DECISIONS.yaml``.

Deterministic: no timestamps; re-running on the same manifests gives the same file.

Excerpts are quoted as extracted (whitespace collapsed, cut to ``EXCERPT_CHARS`` characters).
Control and invisible format characters (Unicode categories Cc, Cf, Cs, Co, Cn; e.g. a NUL
from a legacy, non-Unicode font) are shown as visible escapes (``\\x00``, ``\\u200b``), with a
note under the excerpt: nothing is dropped or replaced, and the Markdown stays plain text.

Usage: python scripts/doc_review_package.py <batch>
"""

from __future__ import annotations

import argparse
import json
import unicodedata
from pathlib import Path

from civicmind.catalog.documents import read_document_manifests
from civicmind.rag.doc_intake import load_intake

ROOT = Path(__file__).resolve().parents[1]
EXCERPT_PAGES = 2
EXCERPT_CHARS = 240
#: Unicode categories shown as escapes in excerpts: control, format (invisible), surrogate,
#: private use, unassigned.
ESCAPED_CATEGORIES = frozenset({"Cc", "Cf", "Cs", "Co", "Cn"})
ESCAPE_NOTE = (
    "Control or invisible characters in the extracted text are shown as `\\xNN` / `\\uNNNN`"
    " escapes (as found; nothing removed)."
)


def _pages(pages: list[int]) -> str:
    """Compact page ranges: [1, 2, 3, 7] -> '1-3, 7'."""
    out, start, prev = [], None, None
    for p in sorted(pages):
        if start is None:
            start = prev = p
        elif p == prev + 1:
            prev = p
        else:
            out.append(f"{start}-{prev}" if start != prev else str(start))
            start = prev = p
    if start is not None:
        out.append(f"{start}-{prev}" if start != prev else str(start))
    return ", ".join(out)


def visible(text: str) -> str:
    """``text`` with control and invisible format characters written as escapes."""
    out = []
    for c in text:
        if unicodedata.category(c) in ESCAPED_CATEGORIES:
            out.append(f"\\x{ord(c):02x}" if ord(c) < 0x100 else f"\\u{ord(c):04x}")
        else:
            out.append(c)
    return "".join(out)


def _excerpt(root: Path, output_path: str) -> tuple[list[str], bool]:
    """The first excerpt lines, and whether any character in them had to be escaped."""
    lines, escaped = [], False
    for raw in (root / output_path).read_text(encoding="utf-8").splitlines():
        record = json.loads(raw)
        # Cut to the limit, then drop a space the cut may leave at the end (no trailing
        # whitespace in the Markdown); whitespace is already collapsed, so nothing else changes.
        text = " ".join(record["text"].split())[:EXCERPT_CHARS].rstrip()
        if len(text) >= 20:
            shown = visible(text)
            escaped = escaped or shown != text
            lines.append(f"p{record['page']}: {shown}")
        if len(lines) == EXCERPT_PAGES:
            break
    return lines, escaped


def build(batch: str, root: Path = ROOT) -> str:
    ids = [
        d.document_id
        for d in load_intake(root / f"docs/acquisition/{batch}/DOCUMENT_INTAKE.yaml").documents
    ]
    manifests = {m.document_id: m for m in read_document_manifests(root) if m.document_id in ids}
    out = [
        f"# Review package: batch {batch}",
        "",
        "Generated by `scripts/doc_review_package.py` from the document manifests.",
        "**Nothing here is a decision.** To approve, quarantine or reject a document, write",
        f"`docs/acquisition/{batch}/DOCUMENT_REVIEW_DECISIONS.yaml` (template at the end),",
        f"then re-run `python scripts/process_doc_batch.py {batch}`. An approval must record",
        "both hashes below;",
        "every warning must be accepted as a caveat or confined to excluded pages.",
        "",
    ]
    template = []
    for doc_id in ids:
        m = manifests.get(doc_id)
        if m is None or m.status in ("planned",):
            out += [
                f"## {doc_id}: {m.status if m else 'no manifest'}",
                "",
                "Not prepared; nothing to review.",
                "",
            ]
            continue
        out += [f"## {doc_id}: {m.title}", ""]
        out += [
            "| | |",
            "|---|---|",
            f"| Status | `{m.status}` (review: `{m.human_review}`) |",
            f"| Issuing authority | {m.issuing_authority} |",
            f"| Source class | `{m.source_class}` |",
            f"| Resource page | {m.resource_page} |",
            f"| Download URL | {m.download_url} |",
            f"| Retrieved | {m.retrieval.retrieved_at} by {m.retrieval.retrieved_by} |",
            f"| Licence | {m.licence.name}: {' '.join(m.licence.evidence.split())} |",
        ]
        if m.integrity:
            out += [
                f"| Source SHA-256 | `{m.integrity.sha256}` |",
                f"| Bytes | {m.integrity.bytes:,} (stated {m.integrity.stated_bytes}) |",
                f"| Pages | {m.integrity.pages} |",
            ]
        if m.extraction:
            e = m.extraction
            out += [
                f"| Page file | `{e.output_path}` |",
                f"| Page-file SHA-256 | `{e.output_sha256}` |",
                f"| Extractor | {e.extractor} {e.extractor_version}, {e.preparation_version} |",
                f"| Pages with text | {e.pages_with_text} of {e.pages} |",
                f"| Pages without text | {_pages(e.pages_without_text) or 'none'} |",
            ]
        out += ["", "**Findings**", ""]
        for f in m.findings:
            d = f.get("details") or {}
            pages = f" (pages {_pages(d['pages'])})" if isinstance(d.get("pages"), list) else ""
            extra = []
            for key in ("kinds", "patterns"):
                for name, kind_pages in (d.get(key) or {}).items():
                    extra.append(f"{name}: {len(kind_pages)} pages")
            if d.get("scripts"):
                extra.append(f"scripts: {', '.join(d['scripts'])}")
            kinds = f" [{'; '.join(extra)}]" if extra else ""
            out.append(f"- `{f['code']}` ({f['severity']}): {f['message']}{pages}{kinds}")
        if (
            m.extraction
            and m.extraction.output_path
            and (root / m.extraction.output_path).is_file()
        ):
            excerpt, escaped = _excerpt(root, m.extraction.output_path)
            out += ["", "**First pages with text** (check the printed title)", ""]
            out += [f"> {line}" for line in excerpt]
            if escaped:
                out += ["", ESCAPE_NOTE]
        out.append("")
        if m.status == "validated" and m.integrity and m.extraction:
            template += [
                f"  {doc_id}:",
                "    decision: approve        # or quarantine / reject",
                f"    sha256: {m.integrity.sha256}",
                f"    extraction_sha256: {m.extraction.output_sha256}",
                f"    accepted_caveats: {sorted(m.warning_codes())}",
                "    excluded_pages: []",
                "    note: <why>",
            ]
    out += [
        "## Decisions template (not applied)",
        "",
        "```yaml",
        "reviewed_by: <person>",
        "reviewed_on: 'YYYY-MM-DD'",
        "decisions:",
        *template,
        "```",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("batch")
    args = parser.parse_args()
    target = ROOT / f"docs/acquisition/{args.batch}/REVIEW_PACKAGE.md"
    target.write_text(build(args.batch), encoding="utf-8", newline="\n")
    print(f"wrote {target.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
